const MONTH_MAP: [RegExp, string][] = [
  [/(^|[^\p{L}])января(?=$|[^\p{L}])/giu, "$1січня"],
  [/(^|[^\p{L}])февраля(?=$|[^\p{L}])/giu, "$1лютого"],
  [/(^|[^\p{L}])марта(?=$|[^\p{L}])/giu, "$1березня"],
  [/(^|[^\p{L}])апреля(?=$|[^\p{L}])/giu, "$1квітня"],
  [/(^|[^\p{L}])мая(?=$|[^\p{L}])/giu, "$1травня"],
  [/(^|[^\p{L}])июня(?=$|[^\p{L}])/giu, "$1червня"],
  [/(^|[^\p{L}])июля(?=$|[^\p{L}])/giu, "$1липня"],
  [/(^|[^\p{L}])августа(?=$|[^\p{L}])/giu, "$1серпня"],
  [/(^|[^\p{L}])сентября(?=$|[^\p{L}])/giu, "$1вересня"],
  [/(^|[^\p{L}])октября(?=$|[^\p{L}])/giu, "$1жовтня"],
  [/(^|[^\p{L}])ноября(?=$|[^\p{L}])/giu, "$1листопада"],
  [/(^|[^\p{L}])декабря(?=$|[^\p{L}])/giu, "$1грудня"],
  [/(^|[^\p{L}])года(?=$|[^\p{L}])/giu, "$1року"],
];

export function ukrainizeToken(token: string): string {
  const trimmed = token.trim();
  if (!trimmed) return trimmed;
  return GENRE_COUNTRY_MAP[trimmed.toLowerCase()] ?? trimmed;
}

export function ukrainizeInfoKey(rawKey: string): string {
  const cleaned = rawKey.replace(/:+$/, "").trim();
  return INFO_KEY_MAP[cleaned.toLowerCase()] ?? cleaned;
}

export function ukrainizeInfoValue(rawKey: string, rawVal: string): string {
  const cleaned = rawVal
    .replace(/\s+,/g, ",")
    .replace(/\s+:/g, ":")
    .replace(/\s{2,}/g, " ")
    .trim();

  const lowerKey = rawKey.replace(/:+$/, "").trim().toLowerCase();

  if (lowerKey === "жанр" || lowerKey === "страна" || lowerKey === "країна") {
    return cleaned
      .split(",")
      .map((part) => ukrainizeToken(part))
      .join(", ");
  }

  if (lowerKey === "дата выхода" || lowerKey.includes("премьера")) {
    let out = cleaned;
    for (const [re, uk] of MONTH_MAP) {
      out = out.replace(re, uk);
    }
    return out;
  }

  if (lowerKey === "время") {
    return cleaned
      .replace(/(^|[^\p{L}])мин\./giu, "$1хв")
      .replace(/(^|[^\p{L}])(час\.|ч\.)/giu, "$1год");
  }

  if (lowerKey === "рейтинги") {
    return cleaned.replace(/Кинопоиск/gi, "Кінопошук");
  }

  if (lowerKey === "возраст") {
    return cleaned
      .replace(/взрослые темы и понятия, но темы не раскрыты/gi, "дорослі теми й поняття, але не розкриті")
      .replace(/только для взрослых/gi, "лише для дорослих")
      .replace(/для всех возрастов/gi, "для будь-якого віку")
      .replace(/зрителям, достигшим/gi, "глядачам, які досягли")
      .replace(/(^|[^\p{L}])лет(?=$|[^\p{L}])/giu, "$1років");
  }

  return cleaned;
}

export function ukrainizeMiscInfo(misc?: string | null): string {
  if (!misc) return "";
  return misc
    .replace(/\s+,/g, ",")
    .split(",")
    .map((part) => ukrainizeToken(part))
    .join(", ");
}

export function ukrainizeSeriesInfo(info?: string | null): string {
  if (!info) return "";
  return info
    .replace(/Завершен\s*\(все серии\)/gi, "Завершено (усі серії)")
    .replace(/(^|[^\p{L}])Завершен(?=$|[^\p{L}])/giu, "$1Завершено")
    .replace(/(^|[^\p{L}])все серии(?=$|[^\p{L}])/giu, "$1усі серії")
    .replace(/(^|[^\p{L}])серии(?=$|[^\p{L}])/giu, "$1серії")
    .replace(/(^|[^\p{L}])серия(?=$|[^\p{L}])/giu, "$1серія")
    .replace(/(^|[^\p{L}])серий(?=$|[^\p{L}])/giu, "$1серій");
}
